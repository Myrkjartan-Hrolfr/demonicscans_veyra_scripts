'use strict';

// Bundles every CommonJS module below src/ into one userscript.
// Usage: node build.js

const fs = require('node:fs');
const path = require('node:path');

const ROOT = __dirname;
const SRC_DIR = path.join(ROOT, 'src');
const HEADER_FILE = path.join(SRC_DIR, 'userscript.header');
const AUTO_BATTLE_EXTRAS_FILE = path.join(ROOT, 'Auto Battle Extras.user.js');
const AUTO_BATTLE_EXTRAS_MODULE = 'features/general/auto-battle-extras.js';
const ENTRY = 'main.js';
const OUT_FILE = path.join(ROOT, 'dist', 'veyra_automation.user.js');

function collectModules(dir) {
  const modules = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const fullPath = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      modules.push(...collectModules(fullPath));
    } else if (entry.isFile() && entry.name.endsWith('.js')) {
      modules.push(fullPath);
    }
  }
  return modules;
}

function moduleId(fullPath) {
  return path.relative(SRC_DIR, fullPath).split(path.sep).join('/');
}

function indent(text, prefix) {
  return text
    .split('\n')
    .map((line) => (line ? prefix + line : line))
    .join('\n');
}

function autoBattleExtrasModuleSource() {
  const legacy = fs
    .readFileSync(AUTO_BATTLE_EXTRAS_FILE, 'utf8')
    .replace(/^\s*\/\/ ==UserScript==[\s\S]*?\/\/ ==\/UserScript==\s*/, '')
    .trim();
  return `'use strict';

module.exports = Object.freeze({
  id: 'auto-battle-extras',
  group: 'Castle event',
  settings: [],

  matches(url) {
    return /\\/occurrence_castle\\.php\\/?$/i.test(url.pathname);
  },

  run(ctx) {
    const win = ctx.win;
    if (!win || win.__veyraAutoBattleExtrasLoaded) return;
    win.__veyraAutoBattleExtrasLoaded = true;
    const window = win;
    const document = ctx.doc;
${indent(legacy, '    ')}
  },
});`;
}

// The runtime resolves relative require() calls against the requiring module,
// exactly like Node does for the tests.
const RUNTIME = `
  const __cache = Object.create(null);

  function __resolve(fromId, request) {
    if (!request.startsWith('.')) throw new Error('Only relative requires are bundled: ' + request);
    const parts = fromId.split('/').slice(0, -1);
    for (const segment of request.split('/')) {
      if (segment === '..') parts.pop();
      else if (segment && segment !== '.') parts.push(segment);
    }
    const id = parts.join('/');
    if (__modules[id]) return id;
    if (__modules[id + '.js']) return id + '.js';
    if (__modules[id + '/index.js']) return id + '/index.js';
    throw new Error('Module not found: ' + request + ' (from ' + fromId + ')');
  }

  function __require(id) {
    if (__cache[id]) return __cache[id].exports;
    const module = { exports: {} };
    __cache[id] = module;
    __modules[id].call(module.exports, module, module.exports, (request) =>
      __require(__resolve(id, request)),
    );
    return module.exports;
  }
`;

function build() {
  const header = fs.readFileSync(HEADER_FILE, 'utf8').trimEnd();
  const files = collectModules(SRC_DIR).sort();
  const ids = files.map(moduleId);
  if (!ids.includes(ENTRY)) throw new Error(`Entry module src/${ENTRY} is missing.`);

  const moduleSources = files.map((file) => {
    const id = moduleId(file);
    const source =
      id === AUTO_BATTLE_EXTRAS_MODULE
        ? autoBattleExtrasModuleSource()
        : fs.readFileSync(file, 'utf8').trimEnd();
    return `  ${JSON.stringify(id)}: function (module, exports, require) {\n${indent(source, '    ')}\n  },`;
  });

  const output = [
    header,
    '',
    '// Generated by build.js from src/. Do not edit this file directly.',
    '(() => {',
    "  'use strict';",
    '',
    '  const __modules = {',
    ...moduleSources,
    '  };',
    RUNTIME,
    `  __require(${JSON.stringify(ENTRY)});`,
    '})();',
    '',
  ].join('\n');

  fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true });
  fs.writeFileSync(OUT_FILE, output);
  return { outFile: OUT_FILE, modules: ids };
}

if (require.main === module) {
  const { outFile, modules } = build();
  console.log(`Built ${path.relative(ROOT, outFile)} from ${modules.length} modules.`);
}

module.exports = { build };
